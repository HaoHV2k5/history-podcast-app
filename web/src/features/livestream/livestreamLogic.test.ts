  // Scenario 4: Chat Polling Cursor Progression
  it('Scenario 4: calculateNextChatCursor advances to latest timestamp or maintains cursor', () => {
    const currentCursor = 1700000000000;

    const messages: LivestreamChatMessage[] = [
      { id: '1', author: 'Khán giả A', role: 'viewer', text: 'Chào kênh!', timestamp: 1700000001000 },
      { id: '2', author: 'Khán giả B', role: 'viewer', text: 'Tập này hay quá', timestamp: 1700000005000 },
      { id: '3', author: 'Khán giả C', role: 'viewer', text: 'Xem từ đâu vậy', timestamp: 1700000003000 },
    ];

    // Must pick the maximum timestamp (1700000005000)
    const nextCursor = calculateNextChatCursor(currentCursor, messages);
    assert.equal(nextCursor, 1700000005000);

    // Empty list preserves current cursor
    const sameCursor = calculateNextChatCursor(currentCursor, []);
    assert.equal(sameCursor, currentCursor);

    // Outdated incoming message doesn't regress cursor
    const olderMessages: LivestreamChatMessage[] = [
      { id: '0', author: 'Cũ', role: 'viewer', text: 'Tin cũ', timestamp: 1699999999000 },
    ];
    const unchangedCursor = calculateNextChatCursor(currentCursor, olderMessages);
    assert.equal(unchangedCursor, currentCursor);
  });

