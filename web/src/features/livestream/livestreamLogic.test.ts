  // Scenario 26: Same-Timestamp Messages Cross-Cycle Protection
  it('Scenario 26: Bounded overlapping window prevents dropped messages with equal timestamps arriving in different polling cycles', () => {
    // Giả lập tình huống:
    // Chu kỳ 1: Backend có Msg A tạo lúc timestamp = 1700000000000.
    // Client poll với since = 0, nhận được Msg A. Con trỏ logicalCursor tăng lên 1700000000000.
    const msgA: LivestreamChatMessage = {
      id: 'msg-uuid-a',
      author: 'Thính giả A',
      role: 'viewer',
      text: 'Lời chào từ Hà Nội',
      timestamp: 1700000000000,
    };
    const cycle1Messages = [msgA];
    const logicalCursor = calculateNextChatCursor(0, cycle1Messages);
    assert.equal(logicalCursor, 1700000000000);

    // Giữa chu kỳ 1 và chu kỳ 2:
    // Msg B được tạo tại Backend tại ĐÚNG CÙNG mili-giây (timestamp = 1700000000000).
    const msgB: LivestreamChatMessage = {
      id: 'msg-uuid-b',
      author: 'Thính giả B',
      role: 'viewer',
      text: 'Chào bạn nhé!',
      timestamp: 1700000000000,
    };

    // Nếu KHÔNG có overlapping window (truyền since = logicalCursor = 1700000000000):
    // Backend lọc: m.getTimestamp() > since => 1700000000000 > 1700000000000 là FALSE!
    // Msg B bị mất vĩnh viễn!

    // Với giải pháp Overlapping Window:
    // Client tính toán since với cửa sổ lùi 1000ms:
    const sinceQuery = calculateOverlappingPollCursor(logicalCursor, 1000);
    assert.equal(sinceQuery, 1700000000000 - 1000);

    // Giả lập Backend trả về các tin nhắn thỏa mãn m.timestamp > sinceQuery (bao gồm cả Msg A và Msg B):
    const backendCycle2Response = [msgA, msgB];

    // Client thực hiện hợp nhất và khử trùng lặp theo ID duy nhất:
    const merged = deduplicateAndSortChatMessages(cycle1Messages, backendCycle2Response);

    // Kết quả: Giữ trọn vẹn cả 2 tin nhắn Msg A và Msg B, không bị rơi rụng và không bị nhân đôi!
    assert.equal(merged.length, 2);
    assert.equal(merged[0].id, 'msg-uuid-a');
    assert.equal(merged[1].id, 'msg-uuid-b');
  });

