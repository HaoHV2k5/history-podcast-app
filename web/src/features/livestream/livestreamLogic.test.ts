  // Scenario 1: Publisher Role Validation
  it('Scenario 1: validatePublisherRole accepts PUBLISHER and rejects SUBSCRIBER', () => {
    // Valid role
    const validPublisher = validatePublisherRole({ role: 'PUBLISHER' });
    assert.equal(validPublisher.valid, true);

    // Case-insensitive valid
    const lowercasePublisher = validatePublisherRole({ role: 'publisher' });
    assert.equal(lowercasePublisher.valid, true);

    // Reject Subscriber
    const subscriber = validatePublisherRole({ role: 'SUBSCRIBER' });
    assert.equal(subscriber.valid, false);
    assert.match(subscriber.reason || '', /không có quyền phát sóng/i);

    // Reject Null or Empty
    const emptyRole = validatePublisherRole({ role: '' });
    assert.equal(emptyRole.valid, false);

    const nullRole = validatePublisherRole(null);
    assert.equal(nullRole.valid, false);
  });

  // Scenario 2: RTC Credential Completeness Validation
  it('Scenario 2: validateRtcCredentials detects complete vs missing connection fields', () => {
    const validCredentials: LivestreamTokenResponse = {
      appId: 'test_agora_app_id_123',
      token: '007eJxTYGCo...',
      agoraChannelName: 'live_channel_456',
      uid: 1001,
      role: 'PUBLISHER',
      expirationSeconds: 3600,
    };

    const result = validateRtcCredentials(validCredentials);
    assert.equal(result.valid, true);
    assert.equal(result.missingFields.length, 0);

    // Missing token and uid
    const incomplete = validateRtcCredentials({
      appId: 'test_agora_app_id_123',
      agoraChannelName: 'live_channel_456',
    });
    assert.equal(incomplete.valid, false);
    assert.deepEqual(incomplete.missingFields.sort(), ['token', 'uid']);

    // Null object
    const nullObj = validateRtcCredentials(null);
    assert.equal(nullObj.valid, false);
    assert.equal(nullObj.missingFields.length, 4);
  });

