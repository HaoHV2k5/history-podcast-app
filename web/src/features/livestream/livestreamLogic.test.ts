  // Scenario 34: validateEndSessionTransition Ownership & Status Verification
  it('Scenario 34: validateEndSessionTransition validates creator ownership and active LIVE status', () => {
    const creatorId = 99;
    const session: Pick<LivestreamSession, 'status' | 'creatorId'> = {
      status: 'LIVE',
      creatorId,
    };

    // Valid: Creator matches and status is LIVE
    const valid = validateEndSessionTransition(session, creatorId);
    assert.equal(valid.canEnd, true);

    // Invalid: User is not the owner Creator
    const unauthorized = validateEndSessionTransition(session, 100);
    assert.equal(unauthorized.canEnd, false);
    assert.match(unauthorized.reason || '', /Chỉ Creator sở hữu phòng/i);

    // Invalid: Session already ENDED
    const alreadyEnded = validateEndSessionTransition(
      { status: 'ENDED', creatorId },
      creatorId
    );
    assert.equal(alreadyEnded.canEnd, false);
    assert.match(alreadyEnded.reason || '', /đã kết thúc trước đó/i);

    // Invalid: Session is not LIVE (e.g. SCHEDULED)
    const scheduled = validateEndSessionTransition(
      { status: 'SCHEDULED' as unknown as LivestreamSession['status'], creatorId },
      creatorId
    );
    assert.equal(scheduled.canEnd, false);
    assert.match(scheduled.reason || '', /Không thể kết thúc phiên ở trạng thái/i);

    // Invalid: Null session
    const nullSession = validateEndSessionTransition(null, creatorId);
    assert.equal(nullSession.canEnd, false);
    assert.match(nullSession.reason || '', /Không tìm thấy thông tin phiên/i);
  });

  // Scenario 35: Stop Broadcasting vs End Session Semantics
  it('Scenario 35: Stop Broadcasting preserves preview tracks while End Session permanently ends', () => {
    // Khẳng định ngữ nghĩa chuẩn theo Milestone M14-L5:
    // 1. Khi Dừng phát sóng (STOP):
    //    - client unpublish & leave Agora channel
    //    - Session status vẫn là 'LIVE' trên Backend
    //    - Preview tracks vẫn giữ nguyên để Creator có thể khởi động lại (Restart Broadcasting)
    const stateAfterStop = {
      sessionStatus: 'LIVE',
      isBroadcasting: false,
      isJoining: false,
      hasTracks: true,
      isSessionEnded: false,
    };
    assert.equal(canRestartBroadcasting(stateAfterStop), true);

    // 2. Khi Kết thúc phiên live (END):
    //    - Backend endSession() xác nhận chuyển sang 'ENDED'
    //    - Tất cả preview tracks được đóng triệt để
    //    - Không được phép phát sóng lại
    const stateAfterEnd = {
      sessionStatus: 'ENDED',
      isBroadcasting: false,
      isJoining: false,
      hasTracks: false,
      isSessionEnded: true,
    };
    assert.equal(canRestartBroadcasting(stateAfterEnd), false);
    assert.equal(isSessionEndedStatus(stateAfterEnd.sessionStatus), true);
  });
